// P208: atrium 명령의 실행 파일 꾸러미(atrium.exe, mtask.exe). Windows에서만 만든다.
// 까닭: Codex는 명령을 Windows PowerShell 5.1로 돌리고, PowerShell은 `atrium`을 atrium.cmd로 풀었다. .cmd는 cmd를 거쳐
//   여러 줄 인자를 첫 줄에서 자르고 " < > | & %를 cmd 문법으로 읽었다(`"<까닭>"`이 리다이렉션이 되어 "지정된 파일을 찾을 수 없습니다").
//   .ps1 꾸러미는 Codex 샌드박스 사용자(실행 정책 Restricted)에서 PSSecurityException으로 막혀 쓸 수 없었다(P208 시험).
//   실행 파일은 cmd도 실행 정책도 거치지 않는다. PowerShell과 cmd는 PATHEXT 순서로 .exe를 .cmd보다 먼저 찾고, Git Bash는 확장자 없는 sh 꾸러미를 쓴다.
// 하는 일: 받은 argv를 JSON으로 env(ATRIUM_ARGV_JSON, 30000자를 넘으면 임시 파일 경로 ATRIUM_ARGV_FILE)에 실어 node <atrium-child.mjs>를 띄우고
//   그 종료 코드로 끝난다(표준 입출력은 물려준다). node와 스크립트 경로는 같은 폴더의 <이름>.target(두 줄, branch.mjs childShims)에서 읽는다.
// 빌드: 공개 저장소에 바이너리를 넣지 않는다. 판이 뜰 때 Windows에 기본으로 있는 .NET Framework 4의 csc.exe로 아래 C# 글을 빌드한다
//   (글이 바뀌었을 때만. <이름>.exe.ver에 글의 해시). csc가 없거나 빌드가 실패하면 실행 파일 없이 .cmd를 그대로 쓴다(atrium help가 --file을 안내한다).
// 남는 한계: Windows PowerShell 5.1은 네이티브 명령에 넘기는 인자 안의 큰따옴표를 이스케이프하지 않는다. 글 안의 "는 빠지거나 인자가 갈릴 수 있다(PowerShell 7.3+는 된다)
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFile } from 'node:child_process';

export const SHIM_NAMES = ['atrium', 'mtask'];
export const SHIM_EXE_SOURCE = `// Atrium board command shim (P208). Generated by the board, built with the .NET Framework csc.exe.
using System;
using System.Diagnostics;
using System.IO;
using System.Text;

static class AtriumShim {
  static string J(string s) {
    var b = new StringBuilder("\\"");
    foreach (char c in s) {
      if (c == '"') b.Append("\\\\\\"");
      else if (c == '\\\\') b.Append("\\\\\\\\");
      else if (c < (char)0x20) b.Append("\\\\u").Append(((int)c).ToString("x4"));
      else b.Append(c);
    }
    return b.Append('"').ToString();
  }
  static int Main(string[] args) {
    string self = Process.GetCurrentProcess().MainModule.FileName;
    string target = Path.ChangeExtension(self, ".target");
    string[] t;
    try { t = File.ReadAllLines(target, Encoding.UTF8); } catch (Exception e) { Console.Error.WriteLine("atrium: cannot read " + target + ": " + e.Message); return 2; }
    if (t.Length < 2) { Console.Error.WriteLine("atrium: bad " + target); return 2; }
    var j = new StringBuilder("[");
    for (int i = 0; i < args.Length; i++) { if (i > 0) j.Append(','); j.Append(J(args[i])); }
    j.Append(']');
    var psi = new ProcessStartInfo(t[0].Trim(), "\\"" + t[1].Trim() + "\\"");
    psi.UseShellExecute = false;
    string tmp = null;
    if (j.Length > 30000) { tmp = Path.GetTempFileName(); File.WriteAllText(tmp, j.ToString(), new UTF8Encoding(false)); psi.EnvironmentVariables["ATRIUM_ARGV_FILE"] = tmp; }
    else psi.EnvironmentVariables["ATRIUM_ARGV_JSON"] = j.ToString();
    try { using (var p = Process.Start(psi)) { p.WaitForExit(); return p.ExitCode; } }
    catch (Exception e) { Console.Error.WriteLine("atrium: cannot start node: " + e.Message); return 2; }
    finally { if (tmp != null) { try { File.Delete(tmp); } catch { } } }
  }
}
`;
export const SHIM_EXE_HASH = crypto.createHash('sha256').update(SHIM_EXE_SOURCE).digest('hex').slice(0, 16);

// .NET Framework 4의 csc.exe(64비트 먼저). 없으면 null
export function findCsc(env = process.env, exists = fs.existsSync) {
  const root = env.SystemRoot || env.windir || 'C:\\Windows';
  for (const fw of ['Framework64', 'Framework']) { const f = path.join(root, 'Microsoft.NET', fw, 'v4.0.30319', 'csc.exe'); if (exists(f)) return f; }
  return null;
}
// 그 폴더의 실행 파일이 지금 글로 빌드된 것인가
export const shimExeCurrent = (dir, name = 'atrium') => { try { return fs.readFileSync(path.join(dir, `${name}.exe.ver`), 'utf8').trim() === SHIM_EXE_HASH && fs.existsSync(path.join(dir, `${name}.exe`)); } catch { return false; } };

// 도는 실행 파일은 덮어쓸 수 없지만 이름은 바꿀 수 있다. 옛 파일은 옆으로 옮기고(다음에 지운다) 새 파일을 둔다
function place(src, dst) {
  try { fs.copyFileSync(src, dst); return; } catch (e) { if (!fs.existsSync(dst)) throw e; }
  fs.renameSync(dst, `${dst}.old-${Date.now()}`);
  fs.copyFileSync(src, dst);
}
function sweepOld(dir) { try { for (const n of fs.readdirSync(dir)) if (/\.exe\.old-\d+$/.test(n)) { try { fs.rmSync(path.join(dir, n), { force: true }); } catch {} } } catch {} }

// dirs의 각 폴더에 atrium.exe·mtask.exe를 둔다(한 번 빌드해 복사). → { ok, built, dirs, why? }. 실패해도 던지지 않는다
export async function ensureShimExe({ dirs, buildDir, platform = process.platform, csc = undefined, log = () => {}, run = execFileP } = {}) {
  if (platform !== 'win32') return { ok: false, why: 'not_windows' };
  const want = (dirs || []).filter(Boolean);
  for (const d of want) sweepOld(d);
  const stale = want.filter((d) => SHIM_NAMES.some((n) => !shimExeCurrent(d, n)));
  if (!stale.length) return { ok: true, built: false, dirs: [] };
  const compiler = csc === undefined ? findCsc() : csc;
  if (!compiler) { log('shim exe: csc.exe not found, keeping .cmd shims'); return { ok: false, why: 'no_csc' }; }
  const work = buildDir || path.join(want[0], '.shim-build');
  try {
    fs.mkdirSync(work, { recursive: true });
    const cs = path.join(work, 'atrium-shim.cs'); const exe = path.join(work, 'atrium-shim.exe');
    fs.writeFileSync(cs, SHIM_EXE_SOURCE);
    try { fs.rmSync(exe, { force: true }); } catch {}
    await run(compiler, ['/nologo', '/target:exe', '/optimize+', `/out:${exe}`, cs]);
    if (!fs.existsSync(exe)) throw new Error('csc produced no exe');
    for (const d of stale) for (const n of SHIM_NAMES) { place(exe, path.join(d, `${n}.exe`)); fs.writeFileSync(path.join(d, `${n}.exe.ver`), SHIM_EXE_HASH); }
    log(`shim exe built (${SHIM_EXE_HASH}) into ${stale.length} folder(s)`);
    return { ok: true, built: true, dirs: stale };
  } catch (e) {
    log(`shim exe build failed: ${String(e && e.message || e).slice(0, 300)}`);
    return { ok: false, why: 'build_failed', error: String(e && e.message || e).slice(0, 300) };
  } finally { try { fs.rmSync(work, { recursive: true, force: true }); } catch {} }
}
function execFileP(cmd, args) {
  return new Promise((resolve, reject) => execFile(cmd, args, { windowsHide: true, timeout: 60000 }, (err, stdout, stderr) => (err ? reject(Object.assign(err, { message: `${err.message} ${stdout || ''} ${stderr || ''}` })) : resolve({ stdout, stderr }))));
}
