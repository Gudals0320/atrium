// P341: 판이 띄운 세션 나무의 프로세스를 멈추기·다시 돌리기·끄기(resource-guard.mjs가 부른다). Windows에서만.
// 방법(기록): Windows에는 프로세스 나무를 멈추는 공개 API가 없다. 스레드마다 SuspendThread를 부르는 길은 그새 생긴 스레드를 놓치고,
//   디버거 붙이기(DebugActiveProcess)는 판이 디버거로 남아야 한다. 그래서 ntdll의 NtSuspendProcess/NtResumeProcess(프로세스의 모든 스레드를
//   함께 멈추고 수를 센다, Process Explorer·Resource Monitor의 "프로세스 일시 중단"과 같은 길)를 부르는 작은 도우미 atrium-proc.exe를
//   atrium.exe(shim-exe.mjs)처럼 Windows에 기본으로 있는 .NET Framework 4의 csc.exe로 판이 빌드한다(바이너리는 저장소에 없다, 글이 바뀔 때만 다시).
//   csc가 없거나 빌드가 실패하면 일시정지 단추를 숨긴다(available() false). 끄기는 도우미가 없으면 node process.kill(TerminateProcess)로 물러선다.
// 안전(P168 규칙): 도우미는 "pid:생성 시각(에포크 ms)" 짝만 받는다. 핸들을 연 뒤 GetProcessTimes의 생성 시각이 준 값과 5ms 넘게 다르면
//   (PID가 다른 프로세스에 다시 쓰였다) 아무것도 하지 않고 mismatch로 답한다. 핸들을 쥔 채 확인하고 바로 동작하므로 확인과 동작 사이에 PID가 바뀌지 않는다.
//   어떤 pid를 넘길지는 부른 쪽이 방금 읽은 세션 나무에서 고른다(판이 띄운 세션 나무 밖은 넘기지 않는다).
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import os from 'node:os';
import { execFile } from 'node:child_process';
import { findCsc } from './shim-exe.mjs';

export const PROC_EXE_SOURCE = `// Atrium board process helper (P341). Generated by the board, built with the .NET Framework csc.exe.
// usage: atrium-proc suspend|resume|kill|check <pid>:<createdMs> ...  → one line per pid: "<pid> ok|mismatch|open_failed:<err>|failed|bad"
//        atrium-proc snapshot  → "#snapshot <utcMs>" then one line per process: pid TAB ppid TAB createdMs(-1 unknown) TAB cpu100ns TAB workingSet TAB basePriority TAB name (P348)
using System;
using System.Runtime.InteropServices;
using System.Text;

static class AtriumProc {
  [DllImport("kernel32.dll", SetLastError = true)] static extern IntPtr OpenProcess(uint access, bool inherit, int pid);
  [DllImport("kernel32.dll")] static extern bool CloseHandle(IntPtr h);
  [DllImport("kernel32.dll", SetLastError = true)] static extern bool GetProcessTimes(IntPtr h, out long created, out long exited, out long kernel, out long user);
  [DllImport("kernel32.dll", SetLastError = true)] static extern bool TerminateProcess(IntPtr h, uint code);
  [DllImport("ntdll.dll")] static extern int NtSuspendProcess(IntPtr h);
  [DllImport("ntdll.dll")] static extern int NtResumeProcess(IntPtr h);
  [DllImport("ntdll.dll")] static extern int NtQuerySystemInformation(int cls, IntPtr buf, int len, out int ret);
  // P348: process table in one kernel call (SystemProcessInformation, 64-bit layout). No handles are opened, nothing is changed.
  static int Snapshot() {
    if (IntPtr.Size != 8) { Console.Error.WriteLine("atrium-proc: snapshot needs a 64-bit process"); return 3; }
    int len = 1 << 20; IntPtr buf = IntPtr.Zero;
    for (int tries = 0; tries < 8 && buf == IntPtr.Zero; tries++) {
      IntPtr b = Marshal.AllocHGlobal(len); int ret;
      int st = NtQuerySystemInformation(5, b, len, out ret);
      if (st == 0) { buf = b; break; }
      Marshal.FreeHGlobal(b);
      if (st != unchecked((int)0xC0000004)) { Console.Error.WriteLine("atrium-proc: query failed " + st); return 4; }
      len = Math.Max(len * 2, ret + 65536);
    }
    if (buf == IntPtr.Zero) { Console.Error.WriteLine("atrium-proc: buffer too small"); return 4; }
    var o = new StringBuilder(64 * 1024);
    o.Append("#snapshot ").Append((DateTime.UtcNow.Ticks - 621355968000000000L) / 10000).Append('\\n');
    try {
      long off = 0;
      while (true) {
        IntPtr p = new IntPtr(buf.ToInt64() + off);
        int next = Marshal.ReadInt32(p, 0);
        long create = Marshal.ReadInt64(p, 0x20), user = Marshal.ReadInt64(p, 0x28), kern = Marshal.ReadInt64(p, 0x30);
        int nameLen = Marshal.ReadInt16(p, 0x38) & 0xffff;
        IntPtr nameBuf = Marshal.ReadIntPtr(p, 0x40);
        int basePrio = Marshal.ReadInt32(p, 0x48);
        long pid = Marshal.ReadInt64(p, 0x50), ppid = Marshal.ReadInt64(p, 0x58), ws = Marshal.ReadInt64(p, 0x90);
        string name = nameBuf == IntPtr.Zero || nameLen == 0 ? (pid == 0 ? "System Idle Process" : "System") : Marshal.PtrToStringUni(nameBuf, nameLen / 2);
        long ms = create > 0 ? (create - 116444736000000000L) / 10000 : -1;
        o.Append(pid).Append('\\t').Append(ppid).Append('\\t').Append(ms).Append('\\t').Append(user + kern).Append('\\t').Append(ws).Append('\\t').Append(basePrio).Append('\\t').Append(name.Replace('\\t', ' ').Replace('\\n', ' ')).Append('\\n');
        if (next == 0) break;
        off += next;
      }
    } finally { Marshal.FreeHGlobal(buf); }
    var stdout = Console.OpenStandardOutput();
    byte[] bytes = Encoding.UTF8.GetBytes(o.ToString());
    stdout.Write(bytes, 0, bytes.Length); stdout.Flush();
    return 0;
  }
  const uint QUERY_LIMITED = 0x1000, SUSPEND_RESUME = 0x0800, TERMINATE = 0x0001;
  static int Main(string[] args) {
    if (args.Length < 1) { Console.Error.WriteLine("usage: atrium-proc suspend|resume|kill|check pid:createdMs ..."); return 2; }
    string verb = args[0];
    if (verb == "snapshot") return Snapshot();
    if (verb != "suspend" && verb != "resume" && verb != "kill" && verb != "check") { Console.Error.WriteLine("atrium-proc: unknown verb " + verb); return 2; }
    uint access = QUERY_LIMITED | (verb == "kill" ? TERMINATE : verb == "check" ? 0u : SUSPEND_RESUME);
    var o = new StringBuilder();
    for (int i = 1; i < args.Length; i++) {
      string[] p = args[i].Split(':');
      int pid; long want; string st;
      if (p.Length != 2 || !int.TryParse(p[0], out pid) || !long.TryParse(p[1], out want)) st = "bad";
      else {
        IntPtr h = OpenProcess(access, false, pid);
        if (h == IntPtr.Zero) st = "open_failed:" + Marshal.GetLastWin32Error();
        else {
          try {
            long c, e, k, u;
            if (!GetProcessTimes(h, out c, out e, out k, out u)) st = "times_failed";
            else {
              long ms = (c - 116444736000000000L) / 10000;
              if (Math.Abs(ms - want) > 5) st = "mismatch";
              else if (verb == "suspend") st = NtSuspendProcess(h) == 0 ? "ok" : "failed";
              else if (verb == "resume") st = NtResumeProcess(h) == 0 ? "ok" : "failed";
              else if (verb == "kill") st = TerminateProcess(h, 1) ? "ok" : "failed";
              else st = "ok";
            }
          } finally { CloseHandle(h); }
        }
      }
      o.Append(p.Length > 0 ? p[0] : "?").Append(' ').Append(st).Append('\\n');
    }
    Console.Write(o.ToString());
    return 0;
  }
}
`;
export const PROC_EXE_HASH = crypto.createHash('sha256').update(PROC_EXE_SOURCE).digest('hex').slice(0, 16);
export const PROC_VERBS = ['suspend', 'resume', 'kill', 'check'];

// P348: 도우미 snapshot 출력 → { procs: Map(pid → { pid, ppid, ws, name, created, cpu, prio }), at, via: 'native' } | null(읽을 수 없음).
//   줄 모양은 readProcessTable(CIM)과 같다: created 에포크 ms(모르면 null), cpu 100ns(커널+사용자), ws 바이트, prio 기본 우선순위(보통 8, 보통 이하 6). 순수 함수
export function parseSnapshot(out) {
  const lines = String(out || '').split(/\r?\n/);
  const head = (lines[0] || '').match(/^#snapshot (\d+)$/);
  if (!head) return null;
  const procs = new Map();
  for (let i = 1; i < lines.length; i++) {
    const f = lines[i].split('\t');
    if (f.length < 7) continue;
    const pid = Number(f[0]), ppid = Number(f[1]), created = Number(f[2]), cpu = Number(f[3]), ws = Number(f[4]), prio = Number(f[5]);
    if (!Number.isInteger(pid) || pid < 0 || !Number.isInteger(ppid)) continue;
    procs.set(pid, { pid, ppid, ws: Number.isFinite(ws) ? ws : 0, name: f.slice(6).join(' '), created: Number.isFinite(created) && created > 0 ? created : null, cpu: Number.isFinite(cpu) ? cpu : null, prio: Number.isFinite(prio) ? prio : null });
  }
  if (procs.size < 2) return null; // 적어도 System과 자기 자신은 있다
  return { procs, at: Number(head[1]), via: 'native' };
}

// 도우미 출력 → Map(pid → 결과 글). 순수 함수
export function parseProcOut(out) {
  const m = new Map();
  for (const line of String(out || '').split(/\r?\n/)) {
    const x = line.trim().match(/^(\d+)\s+(\S+)$/);
    if (x) m.set(Number(x[1]), x[2]);
  }
  return m;
}
// 넘길 인자("pid:생성 ms"). 생성 시각을 모르는 프로세스는 넘기지 않는다(확인할 수 없다). 순수 함수
export function procArgs(procs) {
  const out = [];
  for (const p of procs || []) if (Number.isInteger(Number(p.pid)) && Number(p.pid) > 0 && Number.isFinite(p.created)) out.push(`${Number(p.pid)}:${Math.round(p.created)}`);
  return out;
}

export class ProcControl {
  // dir: 도우미를 둘 폴더(판 데이터 폴더 아래). run(file, args) → { stdout }. 시험에서 바꿔 넣는다
  constructor({ dir, platform = process.platform, csc = undefined, log = () => {}, run = execFileP } = {}) {
    Object.assign(this, { dir, platform, csc, log, run });
    this.exe = dir ? path.join(dir, 'atrium-proc.exe') : null;
    this.state = 'unknown'; // unknown | building | ready | none
    this.building = null;
  }
  current() { try { return !!this.exe && fs.readFileSync(`${this.exe}.ver`, 'utf8').trim() === PROC_EXE_HASH && fs.existsSync(this.exe); } catch { return false; } }
  available() { return this.state === 'ready'; }
  // 도우미를 (글이 바뀌었으면) 빌드한다. 실패해도 던지지 않는다 → ready | none
  ensure() {
    if (this.state === 'ready' || this.state === 'none') return Promise.resolve(this.state);
    if (this.building) return this.building;
    this.building = (async () => {
      if (this.platform !== 'win32' || !this.exe) { this.state = 'none'; return this.state; }
      if (this.current()) { this.state = 'ready'; return this.state; }
      const compiler = this.csc === undefined ? findCsc() : this.csc;
      if (!compiler) { this.log('proc helper: csc.exe not found, pause is hidden'); this.state = 'none'; return this.state; }
      const work = path.join(this.dir, `.proc-build-${process.pid}`);
      try {
        fs.mkdirSync(work, { recursive: true });
        const cs = path.join(work, 'atrium-proc.cs'); const out = path.join(work, 'atrium-proc.exe');
        fs.writeFileSync(cs, PROC_EXE_SOURCE);
        await this.run(compiler, ['/nologo', '/target:exe', '/optimize+', `/out:${out}`, cs]);
        if (!fs.existsSync(out)) throw new Error('csc produced no exe');
        try { fs.rmSync(this.exe, { force: true }); } catch { fs.renameSync(this.exe, `${this.exe}.old-${Date.now()}`); }
        fs.copyFileSync(out, this.exe);
        fs.writeFileSync(`${this.exe}.ver`, PROC_EXE_HASH);
        this.log(`proc helper built (${PROC_EXE_HASH})`);
        this.state = 'ready';
      } catch (e) {
        this.log(`proc helper build failed: ${String((e && e.message) || e).slice(0, 300)}`);
        this.state = 'none';
      } finally { try { fs.rmSync(work, { recursive: true, force: true }); } catch {} this.building = null; }
      return this.state;
    })();
    return this.building;
  }
  // P348: 프로세스 표 한 번(도우미 snapshot). 도우미가 아직 없거나 실패하면 null(부른 쪽이 PowerShell CIM으로 돌아간다). 여기서 빌드하지는 않는다(ensure는 판이 뜰 때 한 번)
  async snapshot() {
    if (this.state !== 'ready') return null;
    try {
      const r = await this.run(this.exe, ['snapshot'], { maxBuffer: 32 * 1024 * 1024, timeout: 10000 });
      return parseSnapshot(r && r.stdout);
    } catch (e) { this.log(`proc helper snapshot failed: ${String((e && e.message) || e).slice(0, 200)}`); return null; }
  }
  // verb: suspend | resume | kill | check, procs: [{ pid, created }] → Map(pid → ok | mismatch | …). 도우미가 없으면 null
  async call(verb, procs) {
    if (!PROC_VERBS.includes(verb)) throw new Error(`bad verb ${verb}`);
    if ((await this.ensure()) !== 'ready') return null;
    const args = procArgs(procs);
    if (!args.length) return new Map();
    const r = await this.run(this.exe, [verb, ...args]);
    return parseProcOut(r && r.stdout);
  }
}

// 우선순위(B): node의 os.setPriority(Windows에서 프로세스 우선순위 등급). 보통 이하 = PRIORITY_BELOW_NORMAL, 보통 = PRIORITY_NORMAL
export const PRIO = { below: os.constants.priority.PRIORITY_BELOW_NORMAL, normal: os.constants.priority.PRIORITY_NORMAL };
export function setPrio(pid, level, set = os.setPriority) { try { set(Number(pid), PRIO[level]); return true; } catch { return false; } }
export function getPrio(pid, get = os.getPriority) { try { return get(Number(pid)); } catch { return null; } }

function execFileP(cmd, args, opts = {}) {
  return new Promise((resolve, reject) => execFile(cmd, args, { windowsHide: true, timeout: 60000, ...opts }, (err, stdout, stderr) => (err ? reject(Object.assign(err, { message: `${err.message} ${stdout || ''} ${stderr || ''}` })) : resolve({ stdout, stderr }))));
}
